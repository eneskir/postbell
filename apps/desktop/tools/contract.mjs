// Generates src/core/manifest.gen.ts from contracts/manifest.schema.json: `npm run contract`; `--check` exits 1 when it is stale.
import { readFileSync, writeFileSync, renameSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const APP = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMA = join(APP, "..", "..", "contracts", "manifest.schema.json");
const OUT = join(APP, "src", "core", "manifest.gen.ts");

const SUPPORTED = new Set(["type", "const", "enum", "properties", "required", "additionalProperties", "items", "minItems", "maxItems", "minLength", "maxLength", "pattern", "minimum", "maximum"]);
const ANNOTATIONS = new Set(["$schema", "$id", "title", "description"]);

export function checkSchema(s, path = "$", root = true) {
  for (const key of Object.keys(s)) {
    if (SUPPORTED.has(key)) continue;
    if (root && ANNOTATIONS.has(key)) continue;
    throw new Error(`CONTRACT_KEYWORD: ${path}.${key}`);
  }
  if (s.type && !["object", "array", "string", "integer", "number", "boolean"].includes(s.type)) throw new Error(`CONTRACT_TYPE: ${path}`);
  if (!s.type && s.const === undefined && !s.enum) throw new Error(`CONTRACT_UNTYPED: ${path}`);
  if (s.type === "object") {
    if (s.additionalProperties !== false) throw new Error(`CONTRACT_OPEN_OBJECT: ${path}`);
    for (const r of s.required ?? []) if (!s.properties?.[r]) throw new Error(`CONTRACT_REQUIRED_UNKNOWN: ${path}.${r}`);
    for (const [k, v] of Object.entries(s.properties ?? {})) checkSchema(v, `${path}.${k}`, false);
  }
  if (s.type === "array") {
    if (!s.items) throw new Error(`CONTRACT_ARRAY_ITEMS: ${path}`);
    checkSchema(s.items, `${path}[]`, false);
  }
  if (s.pattern !== undefined) new RegExp(s.pattern, "u");
}

export function typeOf(s, indent = "") {
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  switch (s.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "array": {
      const item = typeOf(s.items, indent);
      return `readonly (${item})[]`;
    }
    case "object": {
      const inner = indent + "  ";
      const req = new Set(s.required ?? []);
      const lines = Object.entries(s.properties ?? {}).map(([k, v]) => `${inner}readonly ${k}${req.has(k) ? "" : "?"}: ${typeOf(v, inner)};`);
      return `{\n${lines.join("\n")}\n${indent}}`;
    }
    default:
      throw new Error("CONTRACT_TYPE");
  }
}

export function render(schema) {
  checkSchema(schema);
  const { $schema, $id, title, description, ...rest } = schema;
  return [
    "// Generated by tools/contract.mjs from contracts/manifest.schema.json. Do not edit; run `npm run contract`.",
    'import type { Schema } from "./schema.ts";',
    "",
    `export const manifestSchemaId = ${JSON.stringify($id)};`,
    "",
    `export const manifestSchemaV1: Schema = ${JSON.stringify(rest, null, 2)};`,
    "",
    `export type ManifestV1 = ${typeOf(schema)};`,
    "",
  ].join("\n");
}

function main(args) {
  const text = render(JSON.parse(readFileSync(SCHEMA, "utf8")));
  const now = existsSync(OUT) ? readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : null;
  if (args.includes("--check")) {
    if (now !== text) {
      console.error("contract: manifest.gen.ts differs from the schema; run `npm run contract`");
      process.exit(1);
    }
    console.log("contract: manifest.gen.ts is up to date");
    return;
  }
  if (now !== text) {
    writeFileSync(`${OUT}.tmp`, text);
    renameSync(`${OUT}.tmp`, OUT);
  }
  console.log(`contract written: ${OUT}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
