// Generates src/ui/tokens.gen.css and src/ui/assets.gen.ts: `npm run tokens`; `--check` exits 1 when they are stale.
import { readFileSync, writeFileSync, renameSync, readdirSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const APP = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const NAME = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const WEIGHTS = { Regular: 400, Medium: 500, "Semi Bold": 600, Bold: 700 };
const KINDS = { color: "COLOR", space: "FLOAT", radius: "FLOAT", size: "FLOAT" };

// Nav icons are CSS masks, and a mask file that fails to load leaves the icon invisible; Vite inlines only
// files under 4 KB, so they are inlined with `?inline` whatever their size.
export const ASSET_GROUPS = [
  { dir: "nav", object: "navIcons", type: "IconName", inline: true },
  { dir: "brand", object: "stickers", type: "StickerName" },
  { dir: "empty", object: "emptyDrawings", type: "EmptyDrawingName" },
  { dir: "logo", object: "logos", type: "LogoName" },
];

export function parseTokenFile(raw) {
  if (!raw || !Array.isArray(raw.variables) || !Array.isArray(raw.textStyles)) throw new Error("TOKENS_SHAPE");
  const variables = raw.variables.map((v) => {
    const [kind, ...rest] = String(v.name).split("/");
    if (!(kind in KINDS) || !rest.length || !rest.every((p) => NAME.test(p))) throw new Error(`TOKENS_NAME: ${v.name}`);
    if (v.type !== KINDS[kind]) throw new Error(`TOKENS_TYPE: ${v.name}`);
    if (kind === "color" && !/^#[0-9a-f]{6}$/.test(v.value)) throw new Error(`TOKENS_COLOR: ${v.name}`);
    if (kind !== "color" && !(Number.isFinite(v.value) && v.value >= 0)) throw new Error(`TOKENS_NUMBER: ${v.name}`);
    return { kind, name: v.name, css: `--${[kind, ...rest].join("-")}`, value: v.value };
  });
  const textStyles = raw.textStyles.map((s) => {
    const [kind, name, ...extra] = String(s.name).split("/");
    if (kind !== "text" || !NAME.test(name ?? "") || extra.length) throw new Error(`TOKENS_TEXT_NAME: ${s.name}`);
    const weight = WEIGHTS[s.style];
    if (!weight) throw new Error(`TOKENS_TEXT_STYLE: ${s.name} ${s.style}`);
    if (s.family !== "Inter") throw new Error(`TOKENS_TEXT_FAMILY: ${s.name} ${s.family}`);
    return { name: s.name, css: `--text-${name}`, family: s.family, weight, size: s.size, lineHeight: s.lineHeight };
  });
  const all = [...variables.map((v) => v.css), ...textStyles.map((t) => t.css)];
  if (new Set(all).size !== all.length) throw new Error("TOKENS_DUPLICATE");
  return { variables, textStyles };
}

const HEAD = "Generated by tools/tokens.mjs from tokens/figma.json and src/ui/assets. Do not edit; run `npm run tokens`.";

export function renderCss(tf) {
  const lines = [`/* ${HEAD} */`, ":root {"];
  for (const v of tf.variables) lines.push(`  ${v.css}: ${v.kind === "color" ? v.value : `${v.value}px`};`);
  for (const t of tf.textStyles) lines.push(`  ${t.css}: ${t.weight} ${t.size}px / ${t.lineHeight}px "${t.family}", sans-serif;`);
  lines.push("}", "");
  return lines.join("\n");
}

const ident = (prefix, name) => prefix + name.split("-").map((p) => p[0].toUpperCase() + p.slice(1)).join("");

export function renderTs(assets) {
  const imports = [];
  const blocks = [];
  for (const g of ASSET_GROUPS) {
    const names = assets[g.dir] ?? [];
    if (!names.length) throw new Error(`ASSETS_EMPTY: ${g.dir}`);
    const entries = names.map((n) => {
      if (!NAME.test(n)) throw new Error(`ASSETS_NAME: ${g.dir}/${n}`);
      const id = ident(g.dir, n);
      imports.push(`import ${id} from "./assets/${g.dir}/${n}.svg${g.inline ? "?inline" : ""}";`);
      return `  "${n}": ${id},`;
    });
    blocks.push(`export const ${g.object} = {\n${entries.join("\n")}\n} as const;\nexport type ${g.type} = keyof typeof ${g.object};`);
  }
  return `// ${HEAD}\n${imports.join("\n")}\n\n${blocks.join("\n\n")}\n`;
}

export function readAssets(dir) {
  const out = {};
  for (const g of ASSET_GROUPS) {
    const d = join(dir, g.dir);
    out[g.dir] = existsSync(d) ? readdirSync(d).filter((f) => f.endsWith(".svg")).map((f) => f.slice(0, -4)).sort() : [];
  }
  return out;
}

function main(args) {
  const check = args.includes("--check");
  const tf = parseTokenFile(JSON.parse(readFileSync(join(APP, "tokens", "figma.json"), "utf8")));
  const assets = readAssets(join(APP, "src", "ui", "assets"));
  const outputs = [
    [join(APP, "src", "ui", "tokens.gen.css"), renderCss(tf)],
    [join(APP, "src", "ui", "assets.gen.ts"), renderTs(assets)],
  ];
  let stale = 0;
  for (const [path, content] of outputs) {
    const now = existsSync(path) ? readFileSync(path, "utf8").replace(/\r\n/g, "\n") : null;
    if (now === content) continue;
    if (check) { console.error(`stale: ${path}`); stale++; continue; }
    writeFileSync(`${path}.tmp`, content);
    renameSync(`${path}.tmp`, path);
  }
  const svgCount = Object.values(assets).reduce((a, b) => a + b.length, 0);
  console.log(`tokens: ${tf.variables.length} variables, ${tf.textStyles.length} text styles, ${svgCount} SVGs${check ? `, ${stale} stale files` : ""}`);
  if (stale) process.exit(1);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
